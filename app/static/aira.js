// Floating AIRA panel. The server decides what each asker gets (pages and FAQ for everyone, shared learning for participants);
// this script only keeps the open state and conversation for the current tab, keyed to the signed-in user and workspace.
(function () {
  const PREFIX = "aira:";
  const store = {
    get(k) { try { return JSON.parse(sessionStorage.getItem(k)); } catch { return null; } },
    set(k, v) { try { sessionStorage.setItem(k, JSON.stringify(v)); } catch {} },
    clearOthers(keep) {
      try { Object.keys(sessionStorage).filter(k => k.startsWith(PREFIX) && k !== keep).forEach(k => sessionStorage.removeItem(k)); } catch {}
    },
  };
  const dock = document.getElementById("aira-dock");
  if (!dock) return; // the full AIRA page has its own form

  const key = PREFIX + dock.dataset.scope;
  store.clearOthers(key); // switching persona or workspace never shows another identity's answers
  const state = store.get(key) || { open: false, log: [] };
  const $ = id => document.getElementById(id);
  const panel = $("aira-panel"), fab = $("aira-fab"), log = $("aira-log"), form = $("aira-form"), input = $("aira-q");
  const save = () => store.set(key, state);
  log.dataset.intro = dock.dataset.intro || "";

  function el(tag, cls, text) { const n = document.createElement(tag); if (cls) n.className = cls; if (text) n.textContent = text; return n; }

  function render(entry) {
    if (entry.q) { log.append(el("div", "aira-msg q", entry.q)); return; }
    const m = el("div", "aira-msg a" + (entry.declined ? " declined" : ""), entry.a);
    if (entry.cites && entry.cites.length) {
      const ul = el("ul");
      entry.cites.forEach(c => ul.append(el("li", null, "S" + c.id + " · " + c.title)));
      m.append(ul);
    }
    const links = (entry.links || []).filter(l => /^\/(?!\/)/.test(l.href)); // same-site paths only
    if (links.length) {
      const row = el("div", "aira-links");
      links.forEach(l => { const a = el("a", null, "Open " + l.title); a.href = l.href; a.title = l.about || ""; row.append(a); });
      m.append(row);
    }
    if (entry.note) m.append(el("span", "meta-line", entry.note));
    log.append(m);
  }

  function setOpen(open) {
    state.open = open; save();
    panel.hidden = !open;
    fab.setAttribute("aria-expanded", String(open));
    if (open) { log.scrollTop = log.scrollHeight; input.focus({ preventScroll: true }); }
  }

  state.log.forEach(render);
  dock.hidden = false;
  setOpen(state.open);
  fab.addEventListener("click", () => setOpen(panel.hidden));
  $("aira-close").addEventListener("click", () => { setOpen(false); fab.focus(); });
  $("aira-clear").addEventListener("click", () => { state.log = []; log.replaceChildren(); save(); input.focus(); });
  document.addEventListener("keydown", e => { if (e.key === "Escape" && !panel.hidden) { setOpen(false); fab.focus(); } });

  form.addEventListener("submit", async e => {
    e.preventDefault();
    const q = input.value.trim();
    if (q.length < 3) return;
    const push = entry => { state.log.push(entry); state.log = state.log.slice(-20); save(); render(entry); log.scrollTop = log.scrollHeight; };
    push({ q });
    input.value = ""; input.disabled = true;
    try {
      const res = await fetch(dock.dataset.api, { method: "POST", credentials: "same-origin",
        headers: { "Content-Type": "application/json" }, body: JSON.stringify({ question: q }) });
      const data = await res.json().catch(() => ({}));
      if (!res.ok) {
        push({ declined: true, a: data.error || (res.status === 401 ? "Your session has ended. Sign in again to use AIRA." : "AIRA could not answer just now.") });
      } else {
        push({ a: data.answer, cites: (data.citations || []).map(c => ({ id: c.id, title: c.title })),
               links: (data.links || []).map(l => ({ href: l.href, title: l.title, about: l.about })),
               declined: ["no match", "no answer", "denied", "public"].includes(data.mode),
               note: data.mode === "ai" ? "Generated by " + data.model + ". Check the cited items." : "" });
      }
    } catch {
      push({ declined: true, a: "AIRA could not be reached. Check your connection and try again." });
    } finally {
      input.disabled = false; input.focus();
    }
  });
})();
